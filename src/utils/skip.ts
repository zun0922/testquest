// FR-P2-005 既読スキップの送り速度。
//
// 実機確認（ST-M2-005-TC-001・2026-09-13）で2回の調整を経ている。
//   ①一律 90ms（約11ノード/秒）→「速すぎて何が流れたか追えない」
//   ②260ms＋8ms/字（中央値で約580ms）→「速くなった実感がない」
//      ＝**人が連打する速さ（200〜330ms）より遅く**なっていた。早送りとして意味をなさない
//   ③現行：140ms＋4ms/字（中央値で約300ms・上限500ms）＝連打よりはっきり速く、目では追える
//
// 一律に固定しないのは、短い相槌のような行で無駄に待たされるため。
// **本文が長い行ほど長く留まる**ようにして、読み飛ばしの体感をそろえる。

/** 下限（短い行でも一瞬は見える）。連打（約200〜330ms）より速いこと。 */
export const SKIP_MIN_MS = 140
/** 1文字あたりの追加時間。 */
export const SKIP_PER_CHAR_MS = 4
/** 上限（長い行で待たされすぎない）。 */
export const SKIP_MAX_MS = 500

/**
 * 既読ノードを自動送りするまでの待ち時間（ミリ秒）。
 * 実データの本文は中央値40字・最長196字（全569ノード・2026-09-13 実測）。
 * 中央値で約300ms、最長でも上限500msに収まる。
 */
export function skipDelayMs(text: string): number {
  const len = text?.length ?? 0
  return Math.min(SKIP_MAX_MS, SKIP_MIN_MS + len * SKIP_PER_CHAR_MS)
}
