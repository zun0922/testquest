// FR-P2-005 既読スキップの送り速度。
//
// 実機確認（ST-M2-005-TC-001・2026-09-13）で「速すぎて何が流れたか追えない」とPO判定。
// 当初は一律 90ms（約11ノード/秒）だったが、これは「止まれること」を確かめる速さであって、
// 「目で追える」速さではなかった。E2E は進む・止まるは検証できるが、**速さが人間に合うかは判定できない**。
//
// 一律に遅くしないのは、短い相槌のような行で無駄に待たされるため。
// **本文が長い行ほど長く留まる**ようにして、読み飛ばしの体感をそろえる。

/** 下限（短い行でも一瞬は見える）。 */
export const SKIP_MIN_MS = 260
/** 1文字あたりの追加時間。 */
export const SKIP_PER_CHAR_MS = 8
/** 上限（長い行で待たされすぎない）。 */
export const SKIP_MAX_MS = 1000

/**
 * 既読ノードを自動送りするまでの待ち時間（ミリ秒）。
 * 実データの本文は中央値40字・最長196字（全569ノード・2026-09-13 実測）。
 * 中央値で約580ms、最長でも上限1000msに収まる。
 */
export function skipDelayMs(text: string): number {
  const len = text?.length ?? 0
  return Math.min(SKIP_MAX_MS, SKIP_MIN_MS + len * SKIP_PER_CHAR_MS)
}
